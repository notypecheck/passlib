"""Password hashes used by Postgres for the pg_authid table"""

import re
import stringprep
import unicodedata
from base64 import b64decode, b64encode
from binascii import Error as _BinAsciiError
from hashlib import md5, sha256

import passlib.utils.handlers as uh
from passlib.crypto.digest import compile_hmac, pbkdf2_hmac
from passlib.utils import to_bytes, to_native_str
from passlib.utils.compat import bascii_to_str

__all__ = [
    "postgres_md5",
    "postgres_scram_sha256",
]


class postgres_md5(uh.HasUserContext, uh.StaticHandler):
    """This class implements the Postgres MD5 Password hash, and follows the :ref:`password-hash-api`.

    It does a single round of hashing, and relies on the username as the salt.

    The :meth:`~passlib.ifc.PasswordHash.hash`, :meth:`~passlib.ifc.PasswordHash.genhash`, and :meth:`~passlib.ifc.PasswordHash.verify` methods all require the
    following additional contextual keywords:

    :type user: str
    :param user: name of postgres user account this password is associated with.
    """

    name = "postgres_md5"
    _hash_prefix = "md5"
    checksum_chars = uh.HEX_CHARS
    checksum_size = 32

    def _calc_checksum(self, secret):
        if isinstance(secret, str):
            secret = secret.encode("utf-8")
        user = to_bytes(self.user, "utf-8", param="user")
        return md5(secret + user).hexdigest()


_PROHIBITED = (
    stringprep.in_table_a1,
    stringprep.in_table_c21_c22,
    stringprep.in_table_c3,
    stringprep.in_table_c4,
    stringprep.in_table_c5,
    stringprep.in_table_c6,
    stringprep.in_table_c7,
    stringprep.in_table_c8,
    stringprep.in_table_c9,
)


def _pg_saslprep(secret):
    """Normalize a password as Postgres's pg_saslprep() does.

    This differs from :func:`passlib.utils.saslprep`: C.1.2 is mapped before
    B.1, the checks apply to the string before normalization, and a password
    that fails them, or isn't valid UTF-8, is used unchanged.
    """
    if isinstance(secret, bytes):
        try:
            source = secret.decode("utf-8")
        except UnicodeDecodeError:
            return secret
    else:
        source = secret
        secret = secret.encode("utf-8")
    if source.isascii():
        return secret
    data = "".join(
        " " if stringprep.in_table_c12(c) else "" if stringprep.in_table_b1(c) else c
        for c in source
    )
    if not data or any(test(c) for c in data for test in _PROHIBITED):
        return secret
    is_ral = stringprep.in_table_d1
    if any(is_ral(c) for c in data) and (
        any(stringprep.in_table_d2(c) for c in data)
        or not (is_ral(data[0]) and is_ral(data[-1]))
    ):
        return secret
    return unicodedata.normalize("NFKC", data).encode("utf-8")


class postgres_scram_sha256(  # type: ignore[misc]
    uh.HasRounds, uh.HasRawSalt, uh.HasRawChecksum, uh.GenericHandler
):
    """This class implements the Postgres SCRAM-SHA-256 password hash, and follows the :ref:`password-hash-api`.

    It stores the SCRAM StoredKey and ServerKey (:rfc:`5802`), as Postgres 10 and later
    do with ``password_encryption = scram-sha-256``.

    The :meth:`~passlib.ifc.PasswordHash.using` method accepts the following optional keywords:

    :type salt: bytes
    :param salt:
        Optional salt bytes.
        If not specified, a 16 byte salt will be autogenerated (this is recommended).

    :type salt_size: int
    :param salt_size:
        Optional number of bytes to use when autogenerating new salts.
        Defaults to 16 bytes.

    :type rounds: int
    :param rounds:
        Optional number of rounds to use.
        Defaults to 4096, but must be within ``range(1, 1<<31)``.

    :type relaxed: bool
    :param relaxed:
        By default, providing an invalid value for one of the other
        keywords will result in a :exc:`ValueError`. If ``relaxed=True``,
        and the error can be corrected, a :exc:`~passlib.exc.PasslibHashWarning`
        will be issued instead. Correctable errors include ``rounds``
        that are too small or too large.

    .. versionadded:: 1.10
    """

    name = "postgres_scram_sha256"
    setting_kwds = ("salt", "salt_size", "rounds")
    ident = "SCRAM-SHA-256$"
    checksum_size = 64

    default_salt_size = 16

    default_rounds = 4096
    min_rounds = 1
    max_rounds = 2**31 - 1
    rounds_cost = "linear"

    _hash_regex = re.compile(
        r"^SCRAM-SHA-256\$([1-9][0-9]*):([A-Za-z0-9+/=]*)\$([A-Za-z0-9+/=]+):([A-Za-z0-9+/=]+)$"
    )

    @classmethod
    def from_string(cls, hash):
        hash = to_native_str(hash, "ascii", "hash")
        if not hash.startswith(cls.ident):
            raise uh.exc.InvalidHashError(cls)
        m = cls._hash_regex.match(hash)
        if not m:
            raise uh.exc.MalformedHashError(cls)
        rounds, salt, stored_key, server_key = m.groups()
        try:
            salt = b64decode(salt, validate=True)
            checksum = b64decode(stored_key, validate=True) + b64decode(
                server_key, validate=True
            )
        except _BinAsciiError:
            raise uh.exc.MalformedHashError(cls)
        if len(checksum) != 64:
            raise uh.exc.MalformedHashError(cls)
        return cls(rounds=int(rounds), salt=salt, checksum=checksum)

    def to_string(self):
        salt = bascii_to_str(b64encode(self.salt))
        stored_key = bascii_to_str(b64encode(self.checksum[:32]))
        server_key = bascii_to_str(b64encode(self.checksum[32:]))
        return f"SCRAM-SHA-256${self.rounds}:{salt}${stored_key}:{server_key}"

    def _calc_checksum(self, secret):
        salted = pbkdf2_hmac("sha256", _pg_saslprep(secret), self.salt, self.rounds)
        hmac = compile_hmac("sha256", salted)
        return sha256(hmac(b"Client Key")).digest() + hmac(b"Server Key")
